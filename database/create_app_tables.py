# ============================================================
# HELPER
# ============================================================

def table_exists(table_name):
    cursor.execute("""
        SELECT COUNT(*)
        FROM USER_TABLES
        WHERE TABLE_NAME = :1
    """, [table_name.upper()])

    return cursor.fetchone()[0] > 0


def create_table(name, sql):
    if table_exists(name):
        print(f"[SKIP] {name} already exists.")
        return

    cursor.execute(sql)
    print(f"[CREATED] {name}")


