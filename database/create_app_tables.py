indexes = [
    (
        "IDX_USERS_ROLE",
        "CREATE INDEX IDX_USERS_ROLE ON USERS(ROLE_ID)"
    ),
    (
        "IDX_USERS_DISTRICT",
        "CREATE INDEX IDX_USERS_DISTRICT ON USERS(DISTRICT_ID)"
    ),
    (
        "IDX_ASSESSMENTS_ENGINEER",
        "CREATE INDEX IDX_ASSESSMENTS_ENGINEER ON FIELD_ASSESSMENTS(ENGINEER_ID)"
    ),
    (
        "IDX_ASSESSMENTS_DISTRICT",
        "CREATE INDEX IDX_ASSESSMENTS_DISTRICT ON FIELD_ASSESSMENTS(DISTRICT_ID)"
    ),
    (
        "IDX_ASSESSMENTS_LOCATION",
        "CREATE INDEX IDX_ASSESSMENTS_LOCATION ON FIELD_ASSESSMENTS(LATITUDE, LONGITUDE)"
    ),
    (
        "IDX_ASSESSMENTS_STATUS",
        "CREATE INDEX IDX_ASSESSMENTS_STATUS ON FIELD_ASSESSMENTS(STATUS)"
    ),
    (
        "IDX_RWH_RECOMMENDATIONS_ASSESSMENT",
        "CREATE INDEX IDX_RWH_RECOMMENDATIONS_ASSESSMENT ON RWH_RECOMMENDATIONS(ASSESSMENT_ID)"
    )
]

print("\nCreating indexes...")

for index_name, sql in indexes:
    cursor.execute("""
        SELECT COUNT(*)
        FROM USER_INDEXES
        WHERE INDEX_NAME = :1
    """, [index_name])

    if cursor.fetchone()[0] == 0:
        cursor.execute(sql)
        print(f"[CREATED] {index_name}")
    else:
        print(f"[SKIP] {index_name} already exists.")


